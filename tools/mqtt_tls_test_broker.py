#!/usr/bin/env python3
"""Minimal local MQTT broker stub for mqtt_tls_transport_test (loopback only).

It accepts CONNECT/PINGREQ/PUBLISH/SUBSCRIBE/DISCONNECT, answers CONNACK,
PINGRESP, PUBACK and SUBACK, and records per connection whether the first byte
was a TLS record (0x16) or a plaintext MQTT CONNECT (0x10). Certificates and
keys are generated by the test at run time in a temporary directory.
"""
import argparse
import json
import os
import signal
import socket
import ssl
import sys
import threading

LOCK = threading.Lock()
SNI = {}


def remember_sni(ssl_sock, name, _context):
    with LOCK:
        SNI[id(ssl_sock)] = name


def log(path, entry):
    with LOCK:
        with open(path, "a", encoding="utf-8") as stream:
            stream.write(json.dumps(entry, sort_keys=True) + "\n")


def read_exact(sock, size):
    data = b""
    while len(data) < size:
        chunk = sock.recv(size - len(data))
        if not chunk:
            raise EOFError
        data += chunk
    return data


def read_packet(sock):
    header = read_exact(sock, 1)[0]
    multiplier, length = 1, 0
    for _ in range(4):
        byte = read_exact(sock, 1)[0]
        length += (byte & 0x7F) * multiplier
        if not byte & 0x80:
            break
        multiplier *= 128
    return header, read_exact(sock, length) if length else b""


def remaining(length):
    out = bytearray()
    while True:
        byte = length % 128
        length //= 128
        out.append(byte | (0x80 if length else 0))
        if not length:
            return bytes(out)


def serve_mqtt(sock, log_path, connection_id):
    mqtt5 = False
    while True:
        header, body = read_packet(sock)
        kind = header & 0xF0
        if header == 0x10:
            name_length = int.from_bytes(body[0:2], "big")
            mqtt5 = body[2 + name_length] == 5
            log(log_path, {"id": connection_id, "mqtt": "connect", "version": 5 if mqtt5 else 4})
            sock.sendall(b"\x20\x03\x00\x00\x00" if mqtt5 else b"\x20\x02\x00\x00")
        elif kind == 0xC0:
            sock.sendall(b"\xd0\x00")
        elif kind == 0x30:
            qos = (header >> 1) & 0x03
            topic_length = int.from_bytes(body[0:2], "big")
            if qos:
                packet_id = body[2 + topic_length:4 + topic_length]
                sock.sendall(b"\x40\x02" + packet_id)
        elif kind == 0x80:
            packet_id = body[0:2]
            offset = 2
            if mqtt5:
                offset += 1 + body[2]
            codes = bytearray()
            while offset < len(body):
                topic_length = int.from_bytes(body[offset:offset + 2], "big")
                offset += 2 + topic_length
                codes.append(body[offset] & 0x03)
                offset += 1
            payload = packet_id + (b"\x00" if mqtt5 else b"") + bytes(codes)
            sock.sendall(b"\x90" + remaining(len(payload)) + payload)
        elif kind == 0xE0:
            return
        else:
            log(log_path, {"id": connection_id, "mqtt": "invalid", "header": header})
            return


def handle(raw, args, context, counter):
    connection_id = counter
    raw.settimeout(10)
    entry = {"id": connection_id}
    try:
        first = raw.recv(1, socket.MSG_PEEK)
        entry["first"] = first.hex() if first else "eof"
        log(args.log, dict(entry, event="accepted"))
        if not first:
            return
        sock = raw
        if context is not None:
            try:
                sock = context.wrap_socket(raw, server_side=True)
            except (ssl.SSLError, OSError) as error:
                log(args.log, {"id": connection_id, "handshake": "failed", "error": str(error)})
                return
            with LOCK:
                sni = SNI.pop(id(sock), None)
            log(args.log, {"id": connection_id, "handshake": "ok", "sni": sni})
        serve_mqtt(sock, args.log, connection_id)
    except (EOFError, OSError, ssl.SSLError):
        pass
    finally:
        try:
            raw.close()
        except OSError:
            pass


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=("tls", "plain"), required=True)
    parser.add_argument("--cert")
    parser.add_argument("--key")
    parser.add_argument("--client-ca")
    parser.add_argument("--port-file", required=True)
    parser.add_argument("--log", required=True)
    args = parser.parse_args()

    context = None
    if args.mode == "tls":
        context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        context.load_cert_chain(args.cert, args.key)
        context.sni_callback = remember_sni
        if args.client_ca:
            context.verify_mode = ssl.CERT_REQUIRED
            context.load_verify_locations(args.client_ca)

    listener = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    listener.bind(("127.0.0.1", 0))
    listener.listen(16)
    temporary = args.port_file + ".tmp"
    with open(temporary, "w", encoding="utf-8") as stream:
        stream.write(str(listener.getsockname()[1]))
    os.replace(temporary, args.port_file)

    signal.signal(signal.SIGTERM, lambda *_: os._exit(0))
    counter = 0
    while True:
        raw, _ = listener.accept()
        counter += 1
        threading.Thread(target=handle, args=(raw, args, context, counter), daemon=True).start()


if __name__ == "__main__":
    sys.exit(main())
