#pragma once

// Point mapping (design CQ15): logic/point-mapping.json connects device points with EMS_CORE virtual points.
// ComputeEngine runs it every scan: input mapping (device -> EMS virtual point), then the strategy graphs,
// then output mapping (EMS virtual point -> device control point through the normal write path, with
// clamping, deadband, refresh and readback verification). While a mapping file is present, graph
// controlWrite / pcsWriteback may only target EMS points: device control points belong to the mapping.
// Output EMS points must be read-only (write.enable false): the graph publishes its command there on every
// run that would have written the device, and the mapping acts only on a command from the current scan.
// The device point is written when it differs from the command by more than write.deadband (as a direct
// controlWrite compares with the device's current value), or when write.refreshMs has elapsed.
//
// File (generated by the engineering client from model templates + device bindings + the point tables):
// { "schemaVersion": "1.0", "kind": "point-mapping", "machineCode": "...",
//   "entries": [ { "virtual": "ems.in.pcs[1].p_total", "virtualIndex": 680001, "direction": "in",
//                  "sources": [ { "meterCode": "...", "pointCode": "p_total", "index": 1201 } ],
//                  "aggregate": "sum|min|max|avg", "scale": 1, "offset": 0, "invert": false,
//                  "enum": { "<device value>": <EMS code> }, "validity": { "timeoutMs": 5000 } },
//                { "virtual": "ems.out.pcs[1].p_set_a", "virtualIndex": 685001, "direction": "out",
//                  "sources": [ { ... "index": 1318 } ],
//                  "write": { "min": -178, "max": 178, "deadband": 1, "refreshMs": 1000,
//                             "readback": { "meterCode": "...", "pointCode": "p_a", "index": 1240, "tolerance": 1, "timeoutMs": 3000 } } } ] }
// Enum targets are numeric EMS codes (named EMS enums wait for CQ17).

#include <cstdint>
#include <map>
#include <string>
#include <unordered_map>
#include <vector>

#include "edge_gateway/models.hpp"

namespace edge_gateway {

const std::uint32_t kPointMappingVirtualIndexMin = 680000;
const std::uint32_t kPointMappingVirtualIndexMax = 689999;

struct PointMappingRef {
    std::string meterCode;
    std::string pointCode;
    std::uint32_t index = 0;
};

struct PointMappingEntry {
    std::string virtualName;
    std::uint32_t virtualIndex = 0;
    bool output = false;
    std::vector<PointMappingRef> sources;
    std::string aggregate;  // inputs with several sources: sum / min / max / avg
    double scale = 1.0;
    double offset = 0.0;
    bool invert = false;
    std::map<double, double> enumMap;  // device value -> EMS code
    std::int64_t validityTimeoutMs = 0;  // inputs: a source older than this is invalid (0 = point expiry only)
    // outputs
    bool hasMin = false;
    bool hasMax = false;
    double writeMin = 0.0;
    double writeMax = 0.0;
    double deadband = 0.0;
    std::int64_t refreshMs = 0;  // rewrite at least this often while the graph commands (0 = only when the device differs)
    PointMappingRef readback;
    double readbackTolerance = 0.0;
    std::int64_t readbackTimeoutMs = 3000;
};

struct PointMapping {
    std::string machineCode;
    std::vector<PointMappingEntry> entries;
};

// What the mapping is checked against: one runtime point (device point tables, EMS_CORE included).
struct PointMappingTarget {
    std::string meterCode;
    std::string pointCode;
    std::string protocol;  // "ems_virtual" for EMS_CORE
    bool writable = false;
};
using PointMappingTargets = std::unordered_map<std::uint32_t, PointMappingTarget>;

struct PointMappingProblem {
    std::string rule;  // mapping.format / mapping.points / mapping.write / mapping.enum / mapping.graphWrites / mapping.cluster
    std::string message;
};

// Throws std::invalid_argument (with the entry position) when the file is not a valid mapping.
PointMapping parsePointMapping(const std::string& text);

PointMappingTargets pointMappingTargets(const std::vector<DeviceConfig>& devices);

// Consistency with the point tables: virtual points are EMS_CORE points (680000-689999) whose pointCode is the
// virtual name; sources / readback points exist with the same meterCode and pointCode; output targets are writable;
// one entry per virtual point and per output device point.
std::vector<PointMappingProblem> checkPointMapping(const PointMapping& mapping, const PointMappingTargets& targets,
                                                   const std::string& machineCode);

// Cluster control (emsCluster.controlEnabled): every control target needs a live cluster authority token on each
// write, which only the strategy graph's own controlWrite carries. Output mappings to those targets are refused.
std::vector<PointMappingProblem> checkPointMappingCluster(const PointMapping& mapping, const EmsClusterConfig& cluster);

// Device points a strategy graph writes directly (enabled controlWrite with submitWrites, pcsWriteback).
struct GraphDeviceWrite {
    std::string nodeId;
    std::string nodeType;
    std::uint32_t index = 0;
};
std::vector<GraphDeviceWrite> graphWriteTargets(const std::string& graphJson);

// Mapping arithmetic (shared by ComputeEngine and tests).
// Input: device value(s) -> EMS value. Returns false when an enum has no entry for the value.
bool pointMappingToEms(const PointMappingEntry& entry, double deviceValue, double* emsValue);
// Output: EMS value -> device value (inverse of the input arithmetic, then clamped to write.min/max).
bool pointMappingToDevice(const PointMappingEntry& entry, double emsValue, double* deviceValue);
double pointMappingAggregate(const std::string& aggregate, const std::vector<double>& values);

}  // namespace edge_gateway
